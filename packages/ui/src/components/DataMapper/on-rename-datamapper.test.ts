import type { Mocked } from 'vitest';

import { IVisualizationNode } from '../../models';
import { DocumentDefinitionType } from '../../models/datamapper';
import { IDataMapperMetadata } from '../../models/datamapper/metadata';
import { EntitiesContextResult, IMetadataApi } from '../../providers';
import { DataMapperMetadataService } from '../../services/datamapper-metadata.service';
import { DataMapperStepService } from '../../services/datamapper-step.service';
import { DataMapperValidationStepService } from '../../services/datamapper-validation-step.service';
import { onRenameDataMapper } from './on-rename-datamapper';

describe('onRenameDataMapper', () => {
  const OLD = 'old.xsl';
  const NEW = 'new.xsl';
  const OLD_WRAPPER = 'old-validation-wrapper.xsd';
  const NEW_WRAPPER = 'new-validation-wrapper.xsd';
  const GENERATED = 'Generated by Kaoto DataMapper. Do not edit';

  let files: Record<string, string>;
  let api: Mocked<IMetadataApi>;
  let metadata: IDataMapperMetadata | undefined;
  const vizNode = { data: { definition: { steps: [] } } } as unknown as IVisualizationNode;
  const entitiesContext = {} as EntitiesContextResult;
  let callOrder: string[];

  beforeEach(() => {
    callOrder = [];
    files = { [OLD]: '<xsl:stylesheet/>' };
    metadata = {
      sourceBody: { type: DocumentDefinitionType.Primitive, filePath: [] },
      sourceParameters: {},
      targetBody: { type: DocumentDefinitionType.XML_SCHEMA, filePath: ['a.xsd', 'b.xsd'] },
      xsltPath: OLD,
    };
    api = {
      getMetadata: vi.fn(() => Promise.resolve(metadata)),
      setMetadata: vi.fn(),
      isResourceExist: vi.fn((path: string) => Promise.resolve(files[path] !== undefined)),
      getResourceContent: vi.fn((path: string) => Promise.resolve(files[path])),
      saveResourceContent: vi.fn((path: string, content: string) => {
        files[path] = content;
        return Promise.resolve();
      }),
      deleteResource: vi.fn((path: string) => {
        delete files[path];
        return Promise.resolve(true);
      }),
    } as unknown as Mocked<IMetadataApi>;
    vi.spyOn(DataMapperStepService, 'getDataMapperMetadataId').mockReturnValue('id');
    vi.spyOn(DataMapperStepService, 'updateXsltFileName').mockImplementation(() => {
      callOrder.push('updateXsltFileName');
    });
    vi.spyOn(DataMapperValidationStepService, 'retargetValidationResource').mockImplementation(() => {
      callOrder.push('retarget');
      return true;
    });
    vi.spyOn(DataMapperMetadataService, 'updateXsltPath').mockResolvedValue(undefined);
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it('should move the XSLT file and update the metadata and the step', async () => {
    const renamed = await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(renamed).toBe(true);
    expect(files[NEW]).toBe('<xsl:stylesheet/>');
    expect(files[OLD]).toBeUndefined();
    expect(DataMapperMetadataService.updateXsltPath).toHaveBeenCalledWith(api, 'id', metadata, NEW);
    expect(DataMapperStepService.updateXsltFileName).toHaveBeenCalledWith(vizNode, NEW, entitiesContext);
  });
  it('should reject and leave the old files and the step untouched when saving the new XSLT fails', async () => {
    files[OLD_WRAPPER] = GENERATED;
    api.saveResourceContent.mockRejectedValue(new Error('read only'));

    await expect(onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW)).rejects.toThrow('read only');

    expect(files[OLD]).toBe('<xsl:stylesheet/>');
    expect(files[OLD_WRAPPER]).toBe(GENERATED);
    expect(DataMapperMetadataService.updateXsltPath).not.toHaveBeenCalled();
    expect(DataMapperStepService.updateXsltFileName).not.toHaveBeenCalled();
    expect(api.deleteResource).not.toHaveBeenCalled();
  });

  it('should copy the generated wrapper, retarget the validator before the step update and delete the old wrapper', async () => {
    files[OLD_WRAPPER] = GENERATED;

    await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(files[NEW_WRAPPER]).toBe(GENERATED);
    expect(files[OLD_WRAPPER]).toBeUndefined();
    expect(callOrder).toEqual(['retarget', 'updateXsltFileName']);
  });

  it('should keep the old wrapper when copying it failed', async () => {
    files[OLD_WRAPPER] = GENERATED;
    vi.spyOn(console, 'warn').mockImplementation(() => {});
    api.saveResourceContent.mockImplementation((path: string, content: string) => {
      if (path === NEW_WRAPPER) return Promise.reject(new Error('read only'));
      files[path] = content;
      return Promise.resolve();
    });

    const renamed = await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(renamed).toBe(true);
    expect(files[OLD_WRAPPER]).toBe(GENERATED);
    expect(DataMapperValidationStepService.retargetValidationResource).not.toHaveBeenCalled();
  });

  it('should not touch a user file with the old wrapper name', async () => {
    files[OLD_WRAPPER] = '<xs:schema/>';

    await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(files[OLD_WRAPPER]).toBe('<xs:schema/>');
    expect(files[NEW_WRAPPER]).toBeUndefined();
  });

  it('should not overwrite a user file at the new wrapper path and keep the old wrapper', async () => {
    files[OLD_WRAPPER] = GENERATED;
    files[NEW_WRAPPER] = '<xs:schema/>';

    await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(files[NEW_WRAPPER]).toBe('<xs:schema/>');
    expect(files[OLD_WRAPPER]).toBe(GENERATED);
  });

  it('should do nothing when there is no metadata', async () => {
    metadata = undefined;

    const renamed = await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(renamed).toBe(false);
    expect(api.saveResourceContent).not.toHaveBeenCalled();
    expect(api.deleteResource).not.toHaveBeenCalled();
  });

  it('should do nothing when the old XSLT file does not exist', async () => {
    delete files[OLD];

    const renamed = await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(renamed).toBe(false);
    expect(api.saveResourceContent).not.toHaveBeenCalled();
    expect(DataMapperStepService.updateXsltFileName).not.toHaveBeenCalled();
  });

  it('should do nothing when the old XSLT content can not be read', async () => {
    api.isResourceExist.mockResolvedValue(true);
    api.getResourceContent.mockResolvedValue(undefined as unknown as string);

    const renamed = await onRenameDataMapper(api, vizNode, entitiesContext, OLD, NEW);

    expect(renamed).toBe(false);
    expect(api.saveResourceContent).not.toHaveBeenCalled();
  });
});
