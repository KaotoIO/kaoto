import {
  DocumentDefinition,
  DocumentDefinitionType,
  DocumentType,
  RootElementOption,
} from '../../../models/datamapper/document';
import { XmlSchemaAnalysisService } from './xml-schema-analysis.service';
import { XmlSchemaDocumentService } from './xml-schema-document.service';

export type XmlValidationUri = { kind: 'root'; uri: string } | { kind: 'wrapper'; uri: string; xsd: string };

export interface XmlSchemaWrapperInput {
  filePaths: string[];
  definitionFiles: Record<string, string>;
  rootElement?: RootElementOption;
}

export class XmlSchemaWrapperGeneratorService {
  static getWrapperPath(xsltPath: string): string {
    return xsltPath.replace(/\.xsl$/i, '-validation-wrapper.xsd');
  }

  static isGeneratedWrapper(xsd: string): boolean {
    return xsd.includes('Generated by Kaoto DataMapper') && xsd.includes('Do not edit');
  }

  static computeValidationUri(input: XmlSchemaWrapperInput, wrapperPath: string): XmlValidationUri {
    if (input.filePaths.length === 0) {
      return { kind: 'root', uri: '' };
    }
    if (input.filePaths.length === 1) {
      return { kind: 'root', uri: input.filePaths[0] };
    }

    const normalizedFilePaths = Array.from(new Set(input.filePaths.map((p) => this.normalizePath(p))));

    const normalizedFiles: Record<string, string> = {};
    for (const [p, content] of Object.entries(input.definitionFiles)) {
      normalizedFiles[this.normalizePath(p)] = content;
    }

    // Content-presence check: every normalized path must have non-empty content
    for (const p of normalizedFilePaths) {
      const content = normalizedFiles[p];
      if (!content || content.trim() === '') {
        console.log(`[XmlSchemaWrapperGeneratorService] Missing or empty content for file: ${p}`);
        return { kind: 'root', uri: input.filePaths[0] };
      }
    }

    const analysis = XmlSchemaAnalysisService.analyze(input.definitionFiles);
    if (analysis.errors && analysis.errors.length > 0) {
      console.log('[XmlSchemaWrapperGeneratorService] Schema analysis failed:', analysis.errors);
      return { kind: 'root', uri: input.filePaths[0] };
    }

    // Prepare edges with normalized paths
    const edges = (analysis.edges || []).map((e) => ({
      from: this.normalizePath(e.from),
      to: this.normalizePath(e.to),
    }));

    const sccs = this.getSCCs(normalizedFilePaths, edges);

    const nodeToScc = new Map<string, number>();
    sccs.forEach((scc, i) => {
      for (const node of scc) {
        nodeToScc.set(node, i);
      }
    });

    const sccHasIncoming = new Array(sccs.length).fill(false);
    for (const e of edges) {
      const fromScc = nodeToScc.get(e.from);
      const toScc = nodeToScc.get(e.to);
      if (fromScc !== undefined && toScc !== undefined && fromScc !== toScc) {
        sccHasIncoming[toScc] = true;
      }
    }

    const sources: string[][] = [];
    sccs.forEach((scc, i) => {
      if (!sccHasIncoming[i]) {
        sources.push(scc);
      }
    });

    const entries: string[] = [];
    for (const scc of sources) {
      scc.sort((a, b) => normalizedFilePaths.indexOf(a) - normalizedFilePaths.indexOf(b));
      entries.push(scc[0]);
    }

    // Deterministically sort based on original order
    entries.sort((a, b) => normalizedFilePaths.indexOf(a) - normalizedFilePaths.indexOf(b));

    if (entries.length === 1) {
      const originalIdx = normalizedFilePaths.indexOf(entries[0]);
      return { kind: 'root', uri: input.filePaths[originalIdx] };
    }

    if (entries.length === 0) {
      return { kind: 'root', uri: input.filePaths[0] };
    }

    const docDef = new DocumentDefinition(
      DocumentType.TARGET_BODY,
      DocumentDefinitionType.XML_SCHEMA,
      'target-body',
      input.definitionFiles,
      input.rootElement,
    );

    let rootNamespace = '';
    try {
      const docResult = XmlSchemaDocumentService.createXmlSchemaDocument(docDef);
      const rootElement = docResult.document?.rootElement;
      if (docResult.validationStatus === 'error' || !rootElement) {
        console.log(
          '[XmlSchemaWrapperGeneratorService] Failed to determine root element, falling back to first entry point',
        );
        return { kind: 'root', uri: input.filePaths[0] };
      }
      rootNamespace = rootElement.getQName()?.getNamespaceURI() || '';
    } catch (err) {
      console.log(
        '[XmlSchemaWrapperGeneratorService] Error during Document build, falling back to first entry point:',
        err,
      );
      return { kind: 'root', uri: input.filePaths[0] };
    }

    const originalEntries = entries.map((entry) => {
      const idx = normalizedFilePaths.indexOf(entry);
      return input.filePaths[idx];
    });

    const xsltName =
      wrapperPath
        .replace(/-validation-wrapper\.xsd$/, '.xsl')
        .split('/')
        .pop() || 'xslt';
    const firstComment = `<!-- Generated by Kaoto DataMapper for ${xsltName}. Do not edit; it is regenerated. -->`;

    let schemaTag = `<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema"`;
    if (rootNamespace !== '') {
      schemaTag += ` targetNamespace="${this.escapeXmlAttr(rootNamespace)}"`;
    }
    schemaTag += '>';

    const directives: string[] = [];
    const importedNamespaces = new Set<string>();

    for (const entry of originalEntries) {
      const relativeLocation = this.getRelativePath(wrapperPath, entry);
      const fNs = analysis.fileInfos.get(entry)?.targetNamespace || '';
      const wNs = rootNamespace;

      let directiveStr = '';
      let isImport = false;

      const escapedLocation = this.escapeXmlAttr(relativeLocation);
      const escapedFNs = this.escapeXmlAttr(fNs);

      if (fNs === wNs) {
        directiveStr = `<xs:include schemaLocation="${escapedLocation}"/>`;
      } else if (fNs === '') {
        directiveStr = `<xs:import schemaLocation="${escapedLocation}"/>`;
        isImport = true;
      } else {
        directiveStr = `<xs:import namespace="${escapedFNs}" schemaLocation="${escapedLocation}"/>`;
        isImport = true;
      }

      if (isImport && fNs !== '') {
        if (importedNamespaces.has(fNs)) {
          console.warn(
            `[XmlSchemaWrapperGeneratorService] Warning: namespace ${fNs} is imported multiple times from unconnected entry points. JAXP may ignore secondary imports.`,
          );
          continue;
        }
        importedNamespaces.add(fNs);
      }

      directives.push(directiveStr);
    }

    const xsd = `<?xml version="1.0" encoding="UTF-8"?>
${firstComment}
${schemaTag}
${directives.map((d) => `  ${d}`).join('\n')}
</xs:schema>
`;

    return { kind: 'wrapper', uri: wrapperPath, xsd };
  }

  private static escapeXmlAttr(val: string): string {
    return val
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&apos;');
  }

  private static normalizePath(p: string): string {
    let cleaned = p.replace(/\\/g, '/');
    cleaned = cleaned.replace(/\/+/g, '/');
    const parts = cleaned.split('/');
    const stack: string[] = [];
    for (const part of parts) {
      if (part === '.' || part === '') {
        continue;
      }
      if (part === '..') {
        if (stack.length > 0 && stack[stack.length - 1] !== '..') {
          stack.pop();
        } else {
          stack.push('..');
        }
      } else {
        stack.push(part);
      }
    }
    return stack.join('/');
  }

  private static getRelativePath(fromFile: string, toFile: string): string {
    const fromNorm = this.normalizePath(fromFile);
    const toNorm = this.normalizePath(toFile);

    const fromDirParts = fromNorm.split('/').slice(0, -1);
    const toParts = toNorm.split('/');

    let commonCount = 0;
    while (
      commonCount < fromDirParts.length &&
      commonCount < toParts.length - 1 &&
      fromDirParts[commonCount] === toParts[commonCount]
    ) {
      commonCount++;
    }

    const upCount = fromDirParts.length - commonCount;
    const ups = new Array(upCount).fill('..');
    const remaining = toParts.slice(commonCount);
    const relativeParts = [...ups, ...remaining];
    return relativeParts.join('/');
  }

  private static getSCCs(nodes: string[], edges: { from: string; to: string }[]): string[][] {
    const indexMap = new Map<string, number>();
    const lowlinkMap = new Map<string, number>();
    const onStack = new Set<string>();
    const stack: string[] = [];
    let index = 0;
    const sccs: string[][] = [];

    const adj = new Map<string, string[]>();
    for (const n of nodes) {
      adj.set(n, []);
    }
    for (const e of edges) {
      if (adj.has(e.from) && adj.has(e.to)) {
        adj.get(e.from)!.push(e.to);
      }
    }

    function strongConnect(v: string) {
      indexMap.set(v, index);
      lowlinkMap.set(v, index);
      index++;
      stack.push(v);
      onStack.add(v);

      const neighbors = adj.get(v) || [];
      for (const w of neighbors) {
        if (!indexMap.has(w)) {
          strongConnect(w);
          lowlinkMap.set(v, Math.min(lowlinkMap.get(v)!, lowlinkMap.get(w)!));
        } else if (onStack.has(w)) {
          lowlinkMap.set(v, Math.min(lowlinkMap.get(v)!, indexMap.get(w)!));
        }
      }

      if (lowlinkMap.get(v) === indexMap.get(v)) {
        const scc: string[] = [];
        let w: string;
        do {
          w = stack.pop()!;
          onStack.delete(w);
          scc.push(w);
        } while (w !== v);
        sccs.push(scc);
      }
    }

    for (const n of nodes) {
      if (!indexMap.has(n)) {
        strongConnect(n);
      }
    }

    return sccs;
  }
}
