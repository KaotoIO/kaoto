import {
  DocumentDefinition,
  DocumentDefinitionType,
  DocumentType,
  RootElementOption,
} from '../../../models/datamapper/document';
import { PathUtil } from '../../path-util';
import { XmlSchemaAnalysisReport, XmlSchemaAnalysisService } from './xml-schema-analysis.service';
import { XmlSchemaDocumentService } from './xml-schema-document.service';

/**
 * Result of {@link XmlSchemaWrapperGeneratorService.computeValidationUri}.
 * `warnings` lists the reasons for a fallback or a dropped import. They are meant to be reported
 * by the caller (the generator itself does no logging).
 */
export type XmlValidationUri =
  | { kind: 'root'; uri: string; warnings: string[] }
  | { kind: 'wrapper'; uri: string; xsd: string; warnings: string[] };

export interface XmlSchemaWrapperInput {
  /** Schema files by path. Its key order is the file order (first key is the fallback root). */
  definitionFiles: Record<string, string>;
  rootElement?: RootElementOption;
}

/**
 * Service that handles dynamic generation of thin XML Schema wrappers
 * for multi-file targets that do not form a single reachable graph.
 *
 * The service is pure: it does no I/O and no logging. The schema graph and its entry points are
 * computed by {@link XmlSchemaAnalysisService}.
 */
export class XmlSchemaWrapperGeneratorService {
  /**
   * Computes the filepath where the generated validation wrapper XSD should be stored.
   * The result is never equal to the input, so saving the wrapper can not overwrite the XSLT file,
   * even when the (hand-editable) metadata contains a path that does not end in `.xsl`.
   *
   * @param xsltPath The path to the parent XSLT mapping file.
   * @returns The computed path to the wrapper schema.
   */
  static getWrapperPath(xsltPath: string): string {
    return /\.xsl$/i.test(xsltPath)
      ? xsltPath.replace(/\.xsl$/i, '-validation-wrapper.xsd')
      : `${xsltPath}-validation-wrapper.xsd`;
  }

  /**
   * Checks whether the given XSD content was automatically generated by Kaoto.
   *
   * @param xsd The XML Schema content to inspect.
   * @returns True if it is a generated wrapper, false otherwise.
   */
  static isGeneratedWrapper(xsd: string): boolean {
    return xsd.includes('Generated by Kaoto DataMapper') && xsd.includes('Do not edit');
  }

  /**
   * Computes the validation URI for an XML target body. When multiple unconnected schemas are
   * attached, it generates a thin wrapper XSD pulling them into a single namespace-compliant graph.
   *
   * Falls back to the first (or the single entry point) schema file, with a warning, when the schemas
   * cannot be analysed, have no entry point or the root namespace cannot be determined.
   *
   * Known limitation: when several unconnected entry points share the same non-root namespace, only the
   * first one is imported (JAXP ignores secondary imports of a namespace), the rest are reported as warning.
   *
   * @param input The multi-file schema content and root element configuration.
   * @param wrapperPath The path where the wrapper XSD should be stored.
   * @returns An object describing the validation URI type, any generated content and warnings.
   */
  static computeValidationUri(input: XmlSchemaWrapperInput, wrapperPath: string): XmlValidationUri {
    const warnings: string[] = [];
    const files = Object.keys(input.definitionFiles);
    if (files.length === 0) {
      return { kind: 'root', uri: '', warnings };
    }
    if (files.length === 1) {
      return { kind: 'root', uri: files[0], warnings };
    }

    const analysis = XmlSchemaAnalysisService.analyze(input.definitionFiles);
    if (analysis.errors.length > 0) {
      warnings.push(
        `Schema analysis failed, validating against "${files[0]}" only: ${analysis.errors.map((e) => e.message).join('; ')}`,
      );
      return { kind: 'root', uri: files[0], warnings };
    }

    const entries = XmlSchemaAnalysisService.findEntryPoints(analysis);
    if (entries.length === 0) {
      warnings.push(`No schema entry point found, validating against "${files[0]}" only`);
      return { kind: 'root', uri: files[0], warnings };
    }
    if (entries.length === 1) {
      return { kind: 'root', uri: entries[0], warnings };
    }

    const rootNamespace = this.determineRootNamespace(input, warnings);
    if (rootNamespace === null) {
      return { kind: 'root', uri: files[0], warnings };
    }

    const xsd = this.generateXsdWrapper(entries, rootNamespace, wrapperPath, analysis, warnings);
    return { kind: 'wrapper', uri: wrapperPath, xsd, warnings };
  }

  private static determineRootNamespace(input: XmlSchemaWrapperInput, warnings: string[]): string | null {
    const docDef = new DocumentDefinition(
      DocumentType.TARGET_BODY,
      DocumentDefinitionType.XML_SCHEMA,
      'target-body',
      input.definitionFiles,
      input.rootElement,
    );

    const firstFile = Object.keys(input.definitionFiles)[0];
    try {
      const docResult = XmlSchemaDocumentService.createXmlSchemaDocument(docDef);
      const rootElement = docResult.document?.rootElement;
      if (docResult.validationStatus === 'error' || !rootElement) {
        warnings.push(`Failed to determine the root element, validating against "${firstFile}" only`);
        return null;
      }
      return rootElement.getQName()?.getNamespaceURI() || '';
    } catch (err) {
      warnings.push(`Error while determining the root element, validating against "${firstFile}" only: ${err}`);
      return null;
    }
  }

  private static generateXsdWrapper(
    entries: string[],
    rootNamespace: string,
    wrapperPath: string,
    analysis: XmlSchemaAnalysisReport,
    warnings: string[],
  ): string {
    const xsltName = PathUtil.extractFilename(wrapperPath).replace(/-validation-wrapper\.xsd$/, '.xsl') || 'xslt';
    const sanitizedXsltName = xsltName.replace(/-+/g, '-');
    const firstComment = `<!-- Generated by Kaoto DataMapper for ${sanitizedXsltName}. Do not edit; it is regenerated. -->`;

    let schemaTag = `<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema"`;
    if (rootNamespace !== '') {
      schemaTag += ` targetNamespace="${this.escapeXmlAttr(rootNamespace)}"`;
    }
    schemaTag += '>';

    const directives: string[] = [];
    const importedNamespaces = new Set<string>();

    for (const entry of entries) {
      const relativeLocation = PathUtil.relativePath(wrapperPath, entry);
      const fNs = analysis.fileInfos.get(entry)?.targetNamespace || '';

      const escapedLocation = this.escapeXmlAttr(relativeLocation);
      const escapedFNs = this.escapeXmlAttr(fNs);

      if (fNs === rootNamespace) {
        directives.push(`<xs:include schemaLocation="${escapedLocation}"/>`);
      } else if (fNs === '') {
        directives.push(`<xs:import schemaLocation="${escapedLocation}"/>`);
      } else if (importedNamespaces.has(fNs)) {
        warnings.push(
          `Namespace "${fNs}" is provided by several unconnected schema files, "${entry}" is not part of the validation`,
        );
      } else {
        importedNamespaces.add(fNs);
        directives.push(`<xs:import namespace="${escapedFNs}" schemaLocation="${escapedLocation}"/>`);
      }
    }

    return `<?xml version="1.0" encoding="UTF-8"?>
${firstComment}
${schemaTag}
${directives.map((d) => `  ${d}`).join('\n')}
</xs:schema>
`;
  }

  private static escapeXmlAttr(val: string): string {
    return val
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&apos;');
  }
}
